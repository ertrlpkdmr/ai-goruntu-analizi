# Eksik etiketleri tek tek çevir
translator = GoogleTranslator(source='en', target='tr')
missing = [label for label in labels_en if label not in labels_tr or labels_tr[label] == "YOK"]
print(f"Eksik etiket sayısı: {len(missing)}")

for i, label in enumerate(missing):
    try:
        translated = translator.translate(label)
        labels_tr[label] = translated.strip().capitalize()
    except:
        labels_tr[label] = label.capitalize()
    if (i + 1) % 20 == 0:
        print(f"  {i+1}/{len(missing)} eksik çevrildi...")

